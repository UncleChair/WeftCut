  it("P3 — GPU readback + Tauri IPC throughput", async function () {
    this.timeout(300000);
    const r = await browser.executeAsync((done) => {
      (async () => {
        const out = {};
        const MB = 1024 * 1024;
        const adapter = await navigator.gpu.requestAdapter();
        if (!adapter) return done({ fatal: "no WebGPU adapter" });
        const device = await adapter.requestDevice();
        out.adapter = adapter.info
          ? {
              vendor: adapter.info.vendor,
              architecture: adapter.info.architecture,
              description: adapter.info.description,
            }
          : null;

        // (a) GPU→CPU texture readback at full RGBA16F frame size (the
        // pre-pack upper bound; the designed pipeline packs to P010 on-GPU
        // first and reads back ~6 MB instead).
        async function benchTextureReadback(w, h, iters) {
          const bytesPerRow = Math.ceil((w * 8) / 256) * 256;
          const size = bytesPerRow * h;
          const tex = device.createTexture({
            size: [w, h],
            format: "rgba16float",
            usage: GPUTextureUsage.RENDER_ATTACHMENT | GPUTextureUsage.COPY_SRC,
          });
          {
            const enc = device.createCommandEncoder();
            const pass = enc.beginRenderPass({
              colorAttachments: [
                {
                  view: tex.createView(),
                  loadOp: "clear",
                  storeOp: "store",
                  clearValue: { r: 0.5, g: 0.25, b: 0.125, a: 1 },
                },
              ],
            });
            pass.end();
            device.queue.submit([enc.finish()]);
            await device.queue.onSubmittedWorkDone();
          }
          const buf = device.createBuffer({
            size,
            usage: GPUBufferUsage.COPY_DST | GPUBufferUsage.MAP_READ,
          });
          // warmup
          for (let i = 0; i < 3; i++) {
            const enc = device.createCommandEncoder();
            enc.copyTextureToBuffer(
              { texture: tex },
              { buffer: buf, bytesPerRow, rowsPerImage: h },
              [w, h, 1],
            );
            device.queue.submit([enc.finish()]);
            // eslint-disable-next-line no-await-in-loop
            await buf.mapAsync(GPUMapMode.READ);
            buf.unmap();
          }
          const t0 = performance.now();
          for (let i = 0; i < iters; i++) {
            const enc = device.createCommandEncoder();
            enc.copyTextureToBuffer(
              { texture: tex },
              { buffer: buf, bytesPerRow, rowsPerImage: h },
              [w, h, 1],
            );
            device.queue.submit([enc.finish()]);
            // eslint-disable-next-line no-await-in-loop
            await buf.mapAsync(GPUMapMode.READ);
            buf.unmap();
          }
          const ms = performance.now() - t0;
          tex.destroy();
          buf.destroy();
          return {
            frameMB: +(size / MB).toFixed(2),
            iters,
            ms: Math.round(ms),
            MBps: Math.round(((size * iters) / MB) / (ms / 1000)),
            fps: +(iters / (ms / 1000)).toFixed(1),
          };
        }
        out.texReadback1080 = await benchTextureReadback(1920, 1080, 30);
        out.texReadback4k = await benchTextureReadback(3840, 2160, 10);

        // (b) P010-sized buffer readback (what the post-pack exit reads).
        async function benchBufferReadback(sizeBytes, iters) {
          const src = device.createBuffer({
            size: sizeBytes,
            usage: GPUBufferUsage.COPY_SRC | GPUBufferUsage.COPY_DST,
          });
          const dst = device.createBuffer({
            size: sizeBytes,
            usage: GPUBufferUsage.COPY_DST | GPUBufferUsage.MAP_READ,
          });
          for (let i = 0; i < 3 + iters; i++) {
            if (i === 3) var t0 = performance.now(); // eslint-disable-line no-var
            const enc = device.createCommandEncoder();
            enc.copyBufferToBuffer(src, 0, dst, 0, sizeBytes);
            device.queue.submit([enc.finish()]);
            // eslint-disable-next-line no-await-in-loop
            await dst.mapAsync(GPUMapMode.READ);
            dst.unmap();
          }
          const ms = performance.now() - t0;
          src.destroy();
          dst.destroy();
          return {
            frameMB: +(sizeBytes / MB).toFixed(2),
            iters,
            ms: Math.round(ms),
            MBps: Math.round(((sizeBytes * iters) / MB) / (ms / 1000)),
            fps: +(iters / (ms / 1000)).toFixed(1),
          };
        }
        const P010_1080 = 1920 * 1080 * 3; // 1.5 planes × 2 B/sample
        const P010_4K = 3840 * 2160 * 3;
        out.bufReadback1080 = await benchBufferReadback(P010_1080, 30);
        out.bufReadback4k = await benchBufferReadback(P010_4K, 10);

        // (c) IPC: writeFile(append) of P010-sized chunks — the export's
        // production streaming pattern (raw-body invoke under the hood).
        const T = window.__TAURI__;
        if (!T?.fs?.writeFile || !T?.path?.tempDir) {
          out.ipcError = "window.__TAURI__.fs/path missing (withGlobalTauri plugin APIs absent)";
        } else {
          const tmpDir = await T.path.tempDir();
          async function benchIpc(label, chunkBytes, chunks) {
            const file = await T.path.join(
              tmpDir,
              `weftcut_f16probe_${label}_${Date.now().toString(36)}.bin`,
            );
            const payload = new Uint8Array(chunkBytes);
            for (let i = 0; i < payload.length; i += 4096) payload[i] = i & 0xff;
            await T.fs.writeFile(file, payload.subarray(0, 4096)); // create + warm path
            const t0 = performance.now();
            for (let i = 0; i < chunks; i++) {
              // eslint-disable-next-line no-await-in-loop
              await T.fs.writeFile(file, payload, { append: true });
            }
            const ms = performance.now() - t0;
            try {
              await T.fs.remove(file);
            } catch {
              /* leave temp garbage rather than fail the bench */
            }
            return {
              chunkMB: +(chunkBytes / MB).toFixed(2),
              chunks,
              ms: Math.round(ms),
              MBps: Math.round(((chunkBytes * chunks) / MB) / (ms / 1000)),
            };
          }
          out.ipc1080 = await benchIpc("1080", P010_1080, 20);
          out.ipc4k = await benchIpc("4k", P010_4K, 6);

          // (d) combined per-frame pipeline at 1080p P010: buffer readback →
          // copy out of mapped range → IPC write. The end-to-end exit rate.
          {
            const src = device.createBuffer({
              size: P010_1080,
              usage: GPUBufferUsage.COPY_SRC | GPUBufferUsage.COPY_DST,
            });
            const dst = device.createBuffer({
              size: P010_1080,
              usage: GPUBufferUsage.COPY_DST | GPUBufferUsage.MAP_READ,
            });
            const file = await T.path.join(
              tmpDir,
              `weftcut_f16probe_combined_${Date.now().toString(36)}.bin`,
            );
            await T.fs.writeFile(file, new Uint8Array(4096));
            const host = new Uint8Array(P010_1080);
            const frames = 15;
            const t0 = performance.now();
            for (let i = 0; i < frames; i++) {
              const enc = device.createCommandEncoder();
              enc.copyBufferToBuffer(src, 0, dst, 0, P010_1080);
              device.queue.submit([enc.finish()]);
              // eslint-disable-next-line no-await-in-loop
              await dst.mapAsync(GPUMapMode.READ);
              host.set(new Uint8Array(dst.getMappedRange()));
              dst.unmap();
              // eslint-disable-next-line no-await-in-loop
              await T.fs.writeFile(file, host, { append: true });
            }
            const ms = performance.now() - t0;
            try {
              await T.fs.remove(file);
            } catch {
              /* ignore */
            }
            src.destroy();
            dst.destroy();
            out.combined1080 = {
              frames,
              ms: Math.round(ms),
              MBps: Math.round(((P010_1080 * frames) / MB) / (ms / 1000)),
              fps: +(frames / (ms / 1000)).toFixed(1),
            };
          }
        }
        done(out);
      })().catch((e) => done({ fatal: String((e && e.stack) || e) }));
    });

    console.log("\n[P3] ===== GPU readback + IPC throughput =====");
    if (r.fatal) {
      console.log("[P3] FATAL:", r.fatal);
    } else {
      console.log("[P3] adapter:", JSON.stringify(r.adapter));
      const row = (label, b) =>
        b &&
        console.log(
          `[P3] ${label.padEnd(34)}: ${String(b.MBps).padStart(6)} MB/s  (${b.frameMB ?? b.chunkMB} MB × ${b.iters ?? b.chunks ?? b.frames}, ${b.ms} ms${b.fps ? `, ${b.fps} fps` : ""})`,
        );
      row("texture readback RGBA16F 1080p", r.texReadback1080);
      row("texture readback RGBA16F 4K", r.texReadback4k);
      row("buffer readback P010 1080p", r.bufReadback1080);
      row("buffer readback P010 4K", r.bufReadback4k);
      if (r.ipcError) console.log("[P3] IPC ERROR:", r.ipcError);
      row("IPC writeFile(append) P010 1080p", r.ipc1080);
      row("IPC writeFile(append) P010 4K", r.ipc4k);
      row("combined readback+IPC 1080p", r.combined1080);
      if (r.combined1080) {
        const v =
          r.combined1080.MBps >= 190
            ? "✅ ≥ realtime 1080p30 P010 (190 MB/s)"
            : r.combined1080.MBps >= 60
              ? "🟡 ≥ 0.3× realtime (60 MB/s) — acceptable for offline export"
              : "❌ below the 60 MB/s offline floor — batch frames / shared-memory transport before declaring dead";
        console.log(`[P3] verdict: ${v}`);
      }
    }
    expect(r.fatal).toBeUndefined();
  });

  it("P4 — float16 2D canvas drawImage precision", async function () {
    this.timeout(120000);
    const files = [
      { label: "hevc-main10", file: GRADIENT_HEVC },
      { label: "h264-hi10p", file: GRADIENT_H264 },
    ].filter((f) => fs.existsSync(f.file));
    const results = [];
    for (const c of files) {
      // eslint-disable-next-line no-await-in-loop
      const r = await browser.executeAsync((absPath, done) => {
        (async () => {
          const out = {};
          const { frames, errors } = await window.__probeDecodeFirst(absPath, null);
          if (!frames.length) return done({ error: "no frame decoded", errors });
          const f = frames[0];
          const W = f.codedWidth;
          const H = f.codedHeight;
          out.frameFormat = f.format;

          const rowStats = (data, w) => {
            const distinct = new Set();
            let monotonic = true;
            let prev = -Infinity;
            let minV = Infinity;
            let maxV = -Infinity;
            for (let x = 0; x < w; x++) {
              const v = data[x * 4];
              if (v < prev) monotonic = false;
              prev = v;
              if (v < minV) minV = v;
              if (v > maxV) maxV = v;
              distinct.add(v);
            }
            return { distinct: distinct.size, monotonic, min: minV, max: maxV };
          };

          try {
            const c2 = new OffscreenCanvas(W, H);
            const ctx = c2.getContext("2d", { colorType: "float16" });
            out.ctxAttrs = ctx.getContextAttributes ? ctx.getContextAttributes() : null;
            ctx.drawImage(f, 0, 0);
            // ImageDataSettings uses `pixelFormat` ("rgba-float16"), NOT the
            // context-attribute key `colorType` — unknown dict members are
            // silently ignored and you get unorm8 back (run-1 mistake).
            let id;
            try {
              id = ctx.getImageData(0, H >> 1, W, 1, { pixelFormat: "rgba-float16" });
            } catch (e) {
              out.getImageDataF16Error = String(e);
              id = ctx.getImageData(0, H >> 1, W, 1);
            }
            out.dataCtor = id.data.constructor.name;
            out.pixelFormat = id.pixelFormat ?? null;
            out.f16Row = rowStats(id.data, W);
          } catch (e) {
            out.f16Error = String(e);
          }

          // control: default 8-bit canvas of the same frame
          try {
            const c8 = new OffscreenCanvas(W, H);
            const ctx8 = c8.getContext("2d");
            ctx8.drawImage(f, 0, 0);
            const id8 = ctx8.getImageData(0, H >> 1, W, 1);
            out.u8Row = rowStats(id8.data, W);
          } catch (e) {
            out.u8Error = String(e);
          }

          frames.forEach((fr) => fr.close());
          done(out);
        })().catch((e) => done({ fatal: String((e && e.stack) || e) }));
      }, c.file);
      results.push({ label: c.label, ...r });
    }

    console.log("\n[P4] ===== float16 2D canvas drawImage precision =====");
    if (!results.length) console.log("[P4] SKIPPED: no 10-bit fixtures present");
    for (const r of results) {
      console.log(`[P4] --- ${r.label} ---`);
      if (r.fatal || r.error) {
        console.log("[P4]   ERROR:", r.fatal ?? r.error, r.errors ?? "");
        continue;
      }
      console.log(
        `[P4]   frameFormat=${r.frameFormat} ctxAttrs=${JSON.stringify(r.ctxAttrs)} data=${r.dataCtor} pixelFormat=${r.pixelFormat}`,
      );
      if (r.f16Error) console.log("[P4]   float16 canvas ERROR:", r.f16Error);
      if (r.getImageDataF16Error)
        console.log("[P4]   getImageData(float16) ERROR:", r.getImageDataF16Error);
      if (r.f16Row) {
        const pass = r.f16Row.distinct > 256;
        console.log(
          `[P4]   f16 row: distinct=${r.f16Row.distinct} monotonic=${r.f16Row.monotonic} min=${r.f16Row.min} max=${r.f16Row.max} -> ${
            pass
              ? "✅ drawImage preserved >8-bit"
              : "❌ quantized to ≤8-bit on the drawImage path"
          }`,
        );
      }
      if (r.u8Row)
        console.log(
          `[P4]   u8 control: distinct=${r.u8Row.distinct} min=${r.u8Row.min} max=${r.u8Row.max}`,
        );
    }
    expect(results.every((r) => !r.fatal)).toBe(true);
  });

