// ONE-OFF PROBES (NOT gates) — float16 working-space exploration, P1–P5.
// Spec: docs/superpowers/specs/2026-06-12-float16-pipeline-exploration.md
//
//   P1  VideoFrame.copyTo() of 10-bit frames — can 10-bit pixels reach our
//       memory at all? (HEVC Main10 fixture = likely HW decode; an extra
//       H.264 Hi10P variant = known SW decode path.)
//   P2  Pixi 8.18 rgba16float RenderTexture — can the composite be RGBA16F
//       without forking Pixi? Custom WGSL gradient mesh + raw GPUTexture
//       readback, count distinct float16 steps (>256 = pass).
//   P3  GPU readback + Tauri IPC throughput — is the export exit fast
//       enough? Targets: 1080p30 P010 realtime ≈ 190 MB/s; ≥ 60 MB/s
//       acceptable for offline (0.3× realtime).
//   P4  float16 2D canvas drawImage precision — does the minimal-change
//       snapshot route preserve >8-bit?
//   P5  HDR glass — programmatic half only (matchMedia + canvas configure
//       echo). Visual presentation needs HDR-mode Windows + HDR display.
//
// Self-contained: mediabunny + pixi.js are injected from node_modules as
// blob-URL ES modules (csp is null; withGlobalTauri exposes convertFileSrc
// and the fs/path plugin APIs). Every test passes unconditionally except on
// harness-level failure — we're probing, not gating; verdicts go to stdout.
//
// Run (from apps/desktop/e2e — npx/npm silently drop --spec on Windows):
//   node node_modules\@wdio\cli\bin\wdio.js run wdio.conf.mjs --spec ./tools/float16_probes.e2e.js
//
// The H.264 Hi10P fixture is generated by fixtures/generate.go --gradient-h264:
//   ffmpeg -y -f lavfi -i "nullsrc=size=1920x1080:rate=30:duration=1" \
//     -vf "format=yuv420p10le,geq=lum='(X/(W-1))*1023':cb=512:cr=512,scale=out_color_matrix=bt709:out_range=tv" \
//     -c:v libx264 -profile:v high10 -pix_fmt yuv420p10le \
//     -colorspace bt709 -color_primaries bt709 -color_trc bt709 -color_range tv \
//     -an fixtures/media/test_1080p_gradient10_h264.mp4

